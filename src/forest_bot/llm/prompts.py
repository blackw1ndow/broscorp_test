from forest_bot.forest import MITTEN_PARTS, MITTENS, PARTS, PLACES


def _places_reference() -> str:
    lines = ["- forest — весь ліс"]
    lines += [f"- {p.code} — частина лісу «{p.name}»" for p in PARTS]
    for mitten in MITTENS:
        parts = MITTEN_PARTS[mitten.code]
        where = " і ".join(PLACES[p].name.lower() for p in parts) or "не належить до жодної частини"
        lines.append(f"- {mitten.code} — рукавичка «{mitten.name}» ({where})")
    return "\n".join(lines)


